// Fallback: unknown characters render as a small hollow box.
const FALLBACK = ['#####', '#...#', '#...#', '#...#', '#...#', '#...#', '#####'];

export function glyphFor(ch: string): string[] {
  return RAW[ch] ?? FALLBACK;
}

// Width in pixels of a string drawn at a given integer scale.
export function textWidth(text: string, scale: number): number {
  if (text.length === 0) return 0;
  return text.length * (GLYPH_W + 1) * scale - scale;
}

// Greedy word wrap: returns lines that fit maxWidth pixels at scale.
export function wrapText(text: string, scale: number, maxWidth: number): string[] {
  const words = text.split(' ');
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    const candidate = current === '' ? word : current + ' ' + word;
    if (textWidth(candidate, scale) <= maxWidth || current === '') {
      current = candidate;
    } else {
      lines.push(current);
      current = word;
    }
  }
  if (current !== '') lines.push(current);
  return lines;
}
